package io.github.bryanttang.bpos.printer

/**
 * 把位元組送到印表機的管道。
 *
 * 這裡開一個介面，不違反「不要生成空的 adapter」那條規則（CLAUDE.md 第四節）——
 * 差別在於它現在就有兩個真的實作，而且**硬體型號是真的還不知道**：店家那台要等
 * 按住 FEED 鍵開機印出自我測試頁，才知道是網路、藍牙還是 USB（SPEC 第七節）。
 * 先做網路（最穩也最簡單）與一個錄下內容的假印表機，另外兩種等確認硬體再補，
 * 不預先開空殼。
 *
 * ## `write` 成功不等於印出來了
 *
 * 回傳成功只代表「位元組交給作業系統了」。紙用完、卡紙、蓋子開著，TCP 一樣寫得進去。
 * 要真的知道印出來沒有，得讀印表機的狀態回應（`DLE EOT`），那需要一條讀的路徑，
 * 會跟著列印佇列一起做。在那之前不要把成功當成「單子在客人手上」
 * （SPEC 第七節〈列印佇列與失敗處理〉）。
 *
 * ## 同一時間只能有一個人在寫
 *
 * 實作不保證並行安全。兩份工作同時寫同一條連線，位元組會交錯，印出來是一張亂碼單，
 * 而且看起來像硬體故障。序列化由列印佇列負責：佇列只有一個 worker 逐筆送，
 * UI 上的「重印」也是補一筆工作進佇列，不是直接呼叫這裡。
 */
interface PrinterTransport {
    /**
     * 建立連線。已經連著的話會先關掉舊的再開新的——
     * 店裡的印表機會被拔電、換網段，握著一條早就死掉的連線只會讓下一單靜靜失敗。
     */
    suspend fun connect(): Result<Unit>

    /** 送出 [bytes]。沒連線就失敗，不會自己去連——連線失敗與送出失敗要分得開。 */
    suspend fun write(bytes: ByteArray): Result<Unit>

    /**
     * 關閉連線。沒連線時呼叫也不會出事。
     *
     * 這支刻意不跟 [write] 互斥：印表機不收資料時（紙用完、緩衝區滿）`write` 會卡住，
     * 而 Java 的 socket 沒有寫入逾時，唯一叫得醒它的方法就是從外面把連線關掉。
     * 如果這支要等 [write] 先放手，那就永遠等不到。
     */
    suspend fun disconnect()
}
